local model = require("review.model")

local function loc()
  return { path = "a.js", side = "new", commit = "abc", worktree = true,
           line_start = 2, line_end = 3, snippet = "x\ny" }
end

describe("model", function()
  it("new_comment pending", function()
    local c = model.new_comment(loc(), "hi", false)
    assert.equals("PENDING", c.status)
    assert.equals(1, #c.thread)
    assert.equals("user", c.thread[1].author)
    assert.equals("hi", c.thread[1].body)
    assert.truthy(c.id:match("^c_%x%x%x%x%x%x$"))
    assert.truthy(c.thread[1].id:match("^m_%x%x%x%x%x%x$"))
    assert.equals("a.js", c.path)
  end)

  it("new_comment posted", function()
    assert.equals("POSTED", model.new_comment(loc(), "hi", true).status)
  end)

  it("post pending", function()
    local c = model.new_comment(loc(), "hi", false)
    assert.is_true(model.post(c))
    assert.equals("POSTED", c.status)
    assert.is_false(model.post(c))
  end)

  it("reply posted on RESPONDED", function()
    local c = model.new_comment(loc(), "hi", true)
    c.status = "RESPONDED"
    local m = model.reply(c, "x", true)
    assert.equals("POSTED", c.status)
    assert.is_nil(m.draft)
    assert.equals(2, #c.thread)
  end)

  it("reply draft keeps status", function()
    local c = model.new_comment(loc(), "hi", true)
    c.status = "RESPONDED"
    local m = model.reply(c, "x", false)
    assert.equals("RESPONDED", c.status)
    assert.is_true(m.draft)
    assert.is_true(model.post(c))
    assert.equals("POSTED", c.status)
    for _, msg in ipairs(c.thread) do assert.is_nil(msg.draft) end
  end)

  it("reply on PENDING stays PENDING", function()
    local c = model.new_comment(loc(), "hi", false)
    model.reply(c, "x", true)
    assert.equals("PENDING", c.status)
  end)

  it("resolve and reopen", function()
    local c = model.new_comment(loc(), "hi", true)
    model.reopen(c)
    assert.equals("POSTED", c.status)
    model.resolve(c)
    assert.equals("RESOLVED", c.status)
    model.reopen(c)
    assert.equals("POSTED", c.status)
  end)

  it("delete is tombstone", function()
    local r = model.new_review("feat/x", nil, 1)
    local c = model.new_comment(loc(), "hi", false)
    table.insert(r.comments, c)
    model.delete(c)
    assert.is_true(c.deleted)
    assert.equals(0, #model.visible(r, true))
  end)

  it("edit rules", function()
    local c = model.new_comment(loc(), "hi", false)
    assert.is_true(model.edit_message(c, c.thread[1].id, "edited"))
    assert.equals("edited", c.thread[1].body)
    model.post(c)
    local ok, err = model.edit_message(c, c.thread[1].id, "nope")
    assert.is_false(ok)
    assert.equals("posted", err)
    local d = model.reply(c, "draft", false)
    assert.is_true(model.edit_message(c, d.id, "draft2"))
  end)

  it("visible hides resolved", function()
    local r = model.new_review("feat/x", nil, 1)
    local a = model.new_comment(loc(), "a", true)
    local b = model.new_comment(loc(), "b", true)
    model.resolve(b)
    r.comments = { a, b }
    assert.equals(1, #model.visible(r, false))
    assert.equals(2, #model.visible(r, true))
  end)

  it("find and new_review", function()
    local r = model.new_review("feat/x", "origin/dev", 2)
    assert.equals(1, r.version)
    assert.equals(2, r.number)
    local c = model.new_comment(loc(), "a", true)
    r.comments = { c }
    assert.equals(c, model.find(r, c.id))
    assert.is_nil(model.find(r, "c_000000"))
  end)

  it("has_agent_reply_after", function()
    local c = model.new_comment(loc(), "a", true)
    table.insert(c.thread, { id = "m_aaaaaa", author = "agent", body = "ok", at = "2026-11-25T10:00:00Z" })
    assert.is_true(model.has_agent_reply_after(c, "2026-11-25T09:00:00Z"))
    assert.is_false(model.has_agent_reply_after(c, "2026-11-25T11:00:00Z"))
  end)
end)
