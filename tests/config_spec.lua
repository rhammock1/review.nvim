local config = require("review.config")

describe("config", function()
  it("defaults", function()
    config.setup()
    assert.equals("<leader>rc", config.options.keymaps.comment)
    assert.is_false(config.options.post_on_submit)
  end)

  it("override list replaces", function()
    config.setup({ float_keymaps = { post = { "<C-g>" } } })
    assert.same({ "<C-g>" }, config.options.float_keymaps.post)
    assert.same({ "<CR>" }, config.options.float_keymaps.save_normal)
  end)

  it("false disables", function()
    config.setup({ keymaps = { export = false } })
    assert.is_false(config.options.keymaps.export)
    assert.equals("<leader>rl", config.options.keymaps.list)
  end)

  it("normalizes disabled and string float keys", function()
    config.setup({ float_keymaps = { post = "<C-g>", save_insert = false } })
    assert.same({ "<C-g>" }, config.options.float_keymaps.post)
    assert.same({}, config.options.float_keymaps.save_insert)
    assert.same({ "<CR>" }, config.options.float_keymaps.save_normal)
    config.setup({ float_keymaps = false, keymaps = false, signs = false })
    assert.same({ save_insert = {}, save_normal = {}, post = {}, cancel = {}, scroll_up = {}, scroll_down = {} }, config.options.float_keymaps)
    assert.is_false(config.options.keymaps.comment)
    assert.equals("", config.options.signs.POSTED)
  end)
end)
