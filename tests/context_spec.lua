local h = require("review_test_helpers")
local context = require("review.context")

describe("context", function()
  local repo
  before_each(function()
    repo = h.repo("feat/x")
    vim.cmd("silent! %bwipeout!")
  end)

  it("normal buffer line", function()
    vim.cmd("edit " .. repo .. "/a.txt")
    vim.api.nvim_win_set_cursor(0, { 2, 0 })
    local ctx = assert(context.current())
    assert.equals("a.txt", ctx.path)
    assert.equals(2, ctx.line_start)
    assert.equals(2, ctx.line_end)
    assert.equals("new", ctx.side)
    assert.is_true(ctx.worktree)
    assert.equals("line 2", ctx.snippet)
    assert.equals(repo, ctx.toplevel)
    assert.equals(40, #ctx.commit)
    assert.equals(vim.api.nvim_get_current_win(), ctx.winid)
  end)

  it("visual range", function()
    vim.cmd("edit " .. repo .. "/a.txt")
    local ctx = assert(context.current({ 4, 2 }))
    assert.equals(2, ctx.line_start)
    assert.equals(4, ctx.line_end)
    assert.equals("line 2\nline 3\nline 4", ctx.snippet)
  end)

  it("outside repo", function()
    vim.cmd("enew")
    local ctx, err = context.current()
    assert.is_nil(ctx)
    assert.truthy(err)
  end)

  it("for_buffer on a real file", function()
    vim.cmd("edit " .. repo .. "/a.txt")
    assert.same({ toplevel = repo, path = "a.txt", side = "new" }, context.for_buffer(0))
  end)
end)
