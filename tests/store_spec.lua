local h = require("review_test_helpers")
local store = require("review.store")
local git = require("review.git")
local model = require("review.model")
require("review.config").setup()

describe("store", function()
  local repo
  before_each(function() repo = h.repo("feat/x") end)

  it("branch slug", function()
    assert.equals("feat-a-b", store.slug("feat/a/b"))
    assert.equals("feat/x", git.branch(repo))
    h.sh({ "git", "checkout", "-q", "--detach" }, repo)
    assert.truthy(git.branch(repo):match("^detached%-%x+$"))
  end)

  it("toplevel and sha", function()
    assert.equals(repo, git.toplevel(repo))
    assert.equals(40, #git.sha("HEAD", repo))
    assert.is_nil(git.toplevel(vim.fn.fnamemodify(repo, ":h")))
  end)

  it("active picks highest n", function()
    local d = store.dir(repo)
    vim.fn.mkdir(d, "p")
    h.write(d .. "/2026-11-20-feat-x-1.json", "{}")
    h.write(d .. "/2026-11-24-feat-x-3.json", "{}")
    h.write(d .. "/2026-11-24-feat-y-9.json", "{}")
    assert.truthy(store.active_path(repo, "feat/x"):match("%-feat%-x%-3%.json$"))
    assert.is_nil(store.active_path(repo, "other"))
  end)

  it("new_path increments", function()
    local d = store.dir(repo)
    vim.fn.mkdir(d, "p")
    h.write(d .. "/2026-11-24-feat-x-3.json", "{}")
    local p, n = store.new_path(repo, "feat/x")
    assert.equals(4, n)
    assert.truthy(p:find("/" .. os.date("%Y-%m-%d") .. "-feat-x-4.json", 1, true))
  end)

  it("write then read roundtrip", function()
    local _, p = store.load_active(repo, "feat/x", nil)
    local r = model.new_review("feat/x", nil, 1)
    assert.is_true(store.write(p, r))
    assert.truthy(h.read(p):find('"comments": []', 1, true))
    local back = store.read(p)
    assert.same({}, back.comments)
    assert.equals("feat/x", back.branch)
  end)

  it("read missing returns nil without error", function()
    local r, err = store.read(repo .. "/nope.json")
    assert.is_nil(r)
    assert.is_nil(err)
  end)

  it("write merges disk changes", function()
    local review, p = store.load_active(repo, "feat/x", nil)
    local c = model.new_comment({ path = "a.txt", side = "new", commit = "x", worktree = true,
      line_start = 1, line_end = 1, snippet = "line 1" }, "q?", true)
    review.comments = { c }
    assert.is_true(store.write(p, review))
    -- agent appends a reply directly to the file
    local disk = store.read(p)
    table.insert(disk.comments[1].thread, { id = "m_abcdef", author = "agent", body = "a", at = "2999-01-01T00:00:00Z" })
    disk.comments[1].status = "RESPONDED"
    disk.comments[1].updated_at = "2999-01-01T00:00:00Z"
    h.write(p, vim.json.encode(disk))
    -- neovim writes its (stale) copy
    local ok, merged = store.write(p, review)
    assert.is_true(ok)
    assert.equals(2, #merged.comments[1].thread)
    local final = store.read(p)
    assert.equals(2, #final.comments[1].thread)
    assert.equals("RESPONDED", final.comments[1].status)
  end)

  it("refuses to write over unparseable file", function()
    local review, p = store.load_active(repo, "feat/x", nil)
    vim.fn.mkdir(store.dir(repo), "p")
    h.write(p, "{oops")
    local ok, err = store.write(p, review)
    assert.is_false(ok)
    assert.truthy(err)
    assert.equals("{oops", h.read(p))
    local r, rerr = store.read(p)
    assert.is_nil(r)
    assert.truthy(rerr)
  end)

  it("records last_written mtime", function()
    local review, p = store.load_active(repo, "feat/x", nil)
    store.write(p, review)
    local st = vim.uv.fs_stat(p)
    assert.equals(st.mtime.sec * 1e9 + st.mtime.nsec, store.last_written[p].mtime_ns)
  end)

  it("ensure_ignored idempotent", function()
    store.ensure_ignored(repo)
    store.ensure_ignored(repo)
    local lines = vim.fn.readfile(repo .. "/.git/info/exclude")
    local count = 0
    for _, l in ipairs(lines) do if l == ".review/" then count = count + 1 end end
    assert.equals(1, count)
    vim.fn.mkdir(store.dir(repo), "p")
    h.write(store.dir(repo) .. "/x.json", "{}")
    assert.equals("", h.sh({ "git", "status", "--porcelain" }, repo))
  end)

  it("load_active creates n=1 in memory without writing", function()
    local r, p = store.load_active(repo, "feat/x", "origin/dev")
    assert.equals(1, r.number)
    assert.equals("origin/dev", r.base)
    assert.truthy(p:match("%-feat%-x%-1%.json$"))
    assert.is_nil(vim.uv.fs_stat(p))
  end)
end)
